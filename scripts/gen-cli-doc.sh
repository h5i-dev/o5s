#!/usr/bin/env bash
# Regenerates docs/CLI.md from the binary's own --help (so it can't drift).
#   scripts/gen-cli-doc.sh [path/to/pico2peta]
set -euo pipefail
source "$(dirname "$0")/env.sh"
B=${1:-$CARGO_TARGET_DIR/debug/pico2peta}
OUT="$(dirname "$0")/../docs/CLI.md"
{
  echo "# pico2peta CLI reference"
  echo
  echo "Generated by \`scripts/gen-cli-doc.sh\` from \`pico2peta --help\`; regenerate after changing the CLI."
  echo "The CLI is plumbing over the domain-agnostic core. How a put is stored comes from namespace profiles"
  echo "(\`init --profile/--namespace\`, then \`put --for-name\`), and domain protocols are served by the server's fronts."
  echo
  echo "Exit codes: 0 ok, 1 error, 2 not found/absent, 3 OCC conflict, 4 forbidden (namespace rule or promotion policy), 5 unauthorized."
  echo
  echo '```text'
  "$B" --help
  echo '```'
  for c in $("$B" --help | awk '/^Commands:/{f=1;next} /^$/{f=0} f{print $1}' | grep -v '^help$'); do
    echo
    echo "## \`$c\`"
    echo
    echo '```text'
    "$B" "$c" --help
    echo '```'
    for s in $("$B" "$c" --help | awk '/^Commands:/{f=1;next} /^$/{f=0} f{print $1}' | grep -v '^help$'); do
      echo
      echo "### \`$c $s\`"
      echo
      echo '```text'
      "$B" "$c" "$s" --help
      echo '```'
    done
  done
} > "$OUT"
echo "wrote $OUT"
